  static String getDefaultLocationAsset(String locationName) {
    for (int groupIdx = 0; groupIdx < groups.length; groupIdx++) {
      final group = groups[groupIdx];
      final List<String> locations = List<String>.from(group['locations'] ?? []);
      final locIdx = locations.indexOf(locationName);
      if (locIdx != -1) {
        final gNum = groupIdx + 1;
        final lNum = locIdx + 1;
        return 'assets/images/defaults/group_$gNum/$gNum-$lNum.jpeg';
      }
    }
    return 'assets/images/card_reveal_bg_not_spy.jpeg';
  }
