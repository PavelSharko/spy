  /// Generates a random name combination using persistent pool
  /// with a safe fallback to dynamic generation.
  static String generateRandomName() {
    try {
      return storageService.generatePersistentName(names, qualities);
    } catch (e) {
      final random = Random();
      final String quality = qualities[random.nextInt(qualities.length)];
      final String name = names[random.nextInt(names.length)];
      final combined = '$quality $name';
      return combined[0].toUpperCase() + combined.substring(1);
    }
  }
